// Builds app/engine/who-lms.js from the WHO Child Growth Standards (2006) LMS tables.
// Source tables: WHO Multicentre Growth Reference Study, as redistributed in the
// pygrowup package (BSD). Usage: node scripts/build-who.mjs <path-to-pygrowup/tables>
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: build-who.mjs <tables dir>'); process.exit(1); }
const load = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
const pick = (rows, key) => rows.map(r => [Number(r[key]), Number(r.L), Number(r.M), Number(r.S)]);

const out = {
  wfa: { boys: pick(load('wfa_boys_0_5_zscores.json'), 'Month'), girls: pick(load('wfa_girls_0_5_zscores.json'), 'Month') },
  lhfa: { boys: pick(load('lhfa_boys_0_5_zscores.json'), 'Month'), girls: pick(load('lhfa_girls_0_5_zscores.json'), 'Month') },
  wfl: { boys: pick(load('wfl_boys_0_2_zscores.json'), 'Length'), girls: pick(load('wfl_girls_0_2_zscores.json'), 'Length') },
  wfh: { boys: pick(load('wfh_boys_2_5_zscores.json'), 'Height'), girls: pick(load('wfh_girls_2_5_zscores.json'), 'Height') },
};
const body = `// GENERATED by scripts/build-who.mjs — do not edit by hand.
// WHO Child Growth Standards (2006): rows are [x, L, M, S].
// wfa/lhfa: x = age in completed months (0-60); wfl: x = recumbent length cm (45-110);
// wfh: x = standing height cm (65-120).
export const WHO_LMS = ${JSON.stringify(out)};
`;
fs.writeFileSync(new URL('../app/engine/who-lms.js', import.meta.url), body);
console.log('wrote who-lms.js', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.boys.length])));
