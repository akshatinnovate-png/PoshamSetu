"""Build app/engine/who-velocity.js from WHO's official weight-velocity xlsx files
(WHO Child Growth Standards: Growth velocity, 2009). Usage:
  python3 scripts/build-velocity.py "<dir containing ttt-weight-*-1mon-z.xlsx ...>"
"""
import json, re, sys, os
import openpyxl

DPM = 30.4375
def to_days(tok):
    tok = tok.strip()
    m = re.match(r'(\d+)\s*(wks|wk|mo)?', tok)
    n = int(m.group(1)); unit = m.group(2) or 'mo'
    return n * 7 if unit.startswith('wk') else round(n * DPM)

def parse(path):
    ws = openpyxl.load_workbook(path, data_only=True).active
    rows = []
    for r in list(ws.iter_rows(values_only=True))[1:]:
        if not r or not r[0]: continue
        a, b = re.split(r'\s*[–-]\s*', str(r[0]))
        if 'wks' in b and 'wks' not in a and 'mo' not in a: a = a + ' wks'
        if 'mo' in b and not re.search(r'wks|mo', a): a = a + ' mo'
        rows.append({'from': to_days(a), 'to': to_days(b), 'L': r[1], 'M': r[2], 'S': r[3], 'delta': r[4], 'sd': list(r[5:12]), 'label': str(r[0]).replace('–', '-')})
    return rows

src = sys.argv[1]
out = {}
for months in (1, 2):
    out[f'w{months}'] = {}
    for sex, key in (('M', 'boys'), ('F', 'girls')):
        name = next(f for f in os.listdir(src) if re.search(fr'weight[-_]{key}[-_]{months}mon', f))
        out[f'w{months}'][sex] = parse(os.path.join(src, name))
js = ('// GENERATED by scripts/build-velocity.py from WHO\'s official xlsx files - do not edit.\n'
      '// WHO Child Growth Standards: growth velocity based on weight (2009). Increments in grams.\n'
      '// z = (((x + delta) / M) ** L - 1) / (L * S). w1 = 1-month intervals (0-12 mo), w2 = 2-month (0-24 mo).\n'
      f'export const WHO_VELOCITY = {json.dumps(out)};\n')
open('app/engine/who-velocity.js', 'w').write(js)
print({k: {s: len(v) for s, v in d.items()} for k, d in out.items()}, out['w1']['M'][0], out['w2']['F'][-1])
